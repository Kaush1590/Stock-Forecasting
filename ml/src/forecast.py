"""Forecasting, exchange sessions, and safe model artifact management."""
from __future__ import annotations
from pathlib import Path
import json
import re
import joblib
import numpy as np
import pandas as pd
import torch
from .preprocessing import add_features, transform_input
from .transformer import StockTransformer


def future_sessions(last_date, horizon: int, exchange: str = "NYSE"):
    """Return official exchange sessions. Install pandas-market-calendars."""
    if horizon < 1:
        raise ValueError("horizon must be positive")
    try:
        import pandas_market_calendars as mcal
    except ImportError as exc:
        raise RuntimeError("Install pandas-market-calendars to compute real exchange sessions") from exc
    try:
        cal = mcal.get_calendar(exchange)
    except Exception as exc:
        raise ValueError(f"Unsupported market calendar: {exchange!r}") from exc
    last = pd.Timestamp(last_date)
    if last.tzinfo is not None:
        last = last.tz_localize(None)
    start = (last + pd.Timedelta(days=1)).normalize()
    days = max(30, horizon * 4)
    for _ in range(8):
        dates = cal.valid_days(start_date=start, end_date=start + pd.Timedelta(days=days))
        if len(dates) >= horizon:
            return pd.DatetimeIndex(dates[:horizon]).tz_localize(None)
        days *= 2
    raise RuntimeError("Could not obtain enough exchange sessions")


def forecast_next_sessions(model, feature_df, x_scaler, y_scaler, feature_names,
                           lookback=60, horizon=7, device="cpu", exchange="NYSE"):
    if len(feature_df) < lookback:
        raise ValueError(f"Need at least {lookback} feature rows for prediction")
    latest = transform_input(feature_df, x_scaler, feature_names, y_scaler)[-lookback:]
    model.eval()
    with torch.no_grad():
        predictions = model(torch.as_tensor(latest[None], dtype=torch.float32, device=device)).cpu().numpy()
    if predictions.shape != (1, horizon):
        raise ValueError("Model returned an unexpected forecast shape")
    prices = y_scaler.inverse_transform(predictions.reshape(-1, 1)).ravel()
    dates = future_sessions(feature_df.index[-1], horizon, exchange)
    return pd.DataFrame({"Forecast_Date": dates, "Predicted_Close": prices})


def artifact_slug(ticker):
    slug = re.sub(r"[^A-Za-z0-9_-]", "_", ticker).strip("_")
    if not slug:
        raise ValueError("Invalid ticker for artifact naming")
    return slug


def save_artifacts(directory, ticker, model, x_scaler, y_scaler, feature_names,
                   model_config, train_config, exchange="NYSE"):
    out = Path(directory)
    out.mkdir(parents=True, exist_ok=True)
    slug = artifact_slug(ticker)
    config = {"ticker": ticker, "exchange": exchange, "feature_names": list(feature_names),
              "model_config": model_config, "train_config": train_config,
              "feature_pipeline_version": 2}
    torch.save(model.cpu().state_dict(), out / f"{slug}_weights.pt")
    joblib.dump({"x_scaler": x_scaler, "y_scaler": y_scaler}, out / f"{slug}_scalers.joblib")
    (out / f"{slug}_config.json").write_text(json.dumps(config, indent=2), encoding="utf-8")
    return config


def load_artifacts(directory, ticker, device="cpu"):
    """Load only artifacts generated by this project from a trusted directory.

    joblib/pickle files must never be loaded from untrusted sources.
    """
    base = Path(directory)
    slug = artifact_slug(ticker)
    config = json.loads((base / f"{slug}_config.json").read_text(encoding="utf-8"))
    if config.get("feature_pipeline_version") != 2 or config.get("ticker") != ticker:
        raise ValueError("Incompatible artifact metadata")
    scaler = joblib.load(base / f"{slug}_scalers.joblib")  # trusted local artifacts only
    model = StockTransformer(**config["model_config"])
    try:
        state = torch.load(base / f"{slug}_weights.pt", map_location=device, weights_only=True)
    except TypeError as exc:
        raise RuntimeError("PyTorch with weights_only=True is required") from exc
    model.load_state_dict(state)
    model.to(device).eval()
    return model, scaler["x_scaler"], scaler["y_scaler"], config
